"""Migration and editorial reports, generated from canonical data and the archived snapshot."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from . import yamlio
from .export import legacy_row, match_status
from .model import Atlas, Collection, Selection
from .proposal import check_proposal
from .snapshot import MASTER_COLUMNS, Row, format_long_duration, read_master_csv, write_master_csv

SNAPSHOT_PATH = Path("archive/2026-10-11-handoff/source/Bach_Cantabile_Master_Ground_Revised.csv")
STUDENT_GUIDE = Path("archive/2026-10-11-handoff/editorial/Bach_Cantabile_Student_Guide.md")


def _retired_selections(c: Collection) -> list[Selection]:
    out = []
    for i, r in enumerate(c.retired):
        d = r.get("selection") or {}
        s = Selection.from_yaml(d, str(r.get("former_stage", "")), "retired.yaml", i)
        out.append(s)
    return out


def _reordered(active: list[Selection]) -> set[str]:
    """Selections whose order relative to other snapshot selections changed.

    The longest increasing run of snapshot positions (in current playlist order) is what stayed in order;
    everything else was moved. Insertions and removals elsewhere shift positions but do not count as moves.
    """
    seq = [(s.source_position, s.id) for s in active if s.source_position]
    tails: list[int] = []  # index into seq of the smallest tail of each run length
    prev: list[int] = [-1] * len(seq)
    for i, (pos, _) in enumerate(seq):
        lo, hi = 0, len(tails)
        while lo < hi:
            mid = (lo + hi) // 2
            if seq[tails[mid]][0] < pos:
                lo = mid + 1
            else:
                hi = mid
        prev[i] = tails[lo - 1] if lo else -1
        if lo == len(tails):
            tails.append(i)
        else:
            tails[lo] = i
    keep: set[str] = set()
    k = tails[-1] if tails else -1
    while k != -1:
        keep.add(seq[k][1])
        k = prev[k]
    return {sid for _, sid in seq if sid not in keep}


def snapshot_comparison(atlas: Atlas, c: Collection, snapshot: list[Row]) -> dict[str, Any]:
    active = c.selections()
    positions = c.positions()
    retired = _retired_selections(c)
    by_src: dict[int, tuple[str, Selection]] = {}
    for s in active:
        if s.source_position:
            by_src[s.source_position] = ("active", s)
    for s in retired:
        if s.source_position:
            by_src[s.source_position] = ("retired", s)

    missing = [int(r["position"]) for r in snapshot if int(r["position"]) not in by_src]
    reordered = _reordered(active)
    moved, amended = [], []
    shifted = 0
    rebuilt: list[Row] = []
    for r in snapshot:
        pos = int(r["position"])
        if pos not in by_src:
            continue
        state, s = by_src[pos]
        if state == "retired":
            # A retired selection's stage may no longer exist in the collection; compare content only.
            row = {k: r[k] for k in MASTER_COLUMNS}
        else:
            row = legacy_row(atlas, c, s, pos)
            if positions[s.id] != pos:
                shifted += 1
            if s.id in reordered:
                moved.append((s, pos, positions[s.id]))
        diffs = [k for k in MASTER_COLUMNS if k not in ("position",) and row[k] != r[k]]
        if state == "active" and diffs:
            amended.append((s, pos, diffs))
        rebuilt.append(row)
    new = [s for s in active if not s.source_position]
    identical = not missing and not amended and not new and not retired and not shifted
    if identical:
        identical = write_master_csv(rebuilt) == write_master_csv(snapshot)
    return {
        "active": active,
        "retired": retired,
        "missing": missing,
        "moved": moved,
        "shifted": shifted,
        "amended": amended,
        "new": new,
        "byte_identical": identical,
    }


def migration_report(root: Path, atlas: Atlas, c: Collection) -> str:
    snapshot = read_master_csv(root / SNAPSHOT_PATH)
    cmp = snapshot_comparison(atlas, c, snapshot)
    accounted = len({s.source_position for s in cmp["active"] + cmp["retired"] if s.source_position})
    lines = [
        f"# Migration report — {c.title}",
        "",
        "Generated by `atlas audit`. Compares canonical data with the archived 669-row snapshot",
        f"(`{SNAPSHOT_PATH}`).",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Snapshot rows | {len(snapshot)} |",
        f"| Canonical active selections | {len(cmp['active'])} |",
        f"| Retired selections (kept for provenance) | {len(cmp['retired'])} |",
        f"| Snapshot rows accounted for (active + retired) | {accounted} / {len(snapshot)} |",
        f"| Snapshot rows missing from canonical data | {len(cmp['missing'])} |",
        f"| Selections reordered relative to the snapshot | {len(cmp['moved'])} |",
        f"| Selections whose position number shifted (insertions/removals) | {cmp['shifted']} |",
        f"| Selections with amended fields | {len(cmp['amended'])} |",
        f"| New selections (not in snapshot) | {len(cmp['new'])} |",
        f"| Legacy CSV export byte-identical to snapshot | {'yes' if cmp['byte_identical'] else 'no'} |",
        "",
        "## Stage counts",
        "",
        "| # | Stage | Snapshot | Canonical | Known duration |",
        "|---:|---|---:|---:|---:|",
    ]
    snap_counts: dict[str, int] = {}
    for r in snapshot:
        snap_counts[r["stage"]] = snap_counts.get(r["stage"], 0) + 1
    for st in c.stages:
        dur = sum(s.duration or 0 for s in st.selections)
        lines.append(
            f"| {st.number} | {st.name} | {snap_counts.get(st.name, 0)} | {len(st.selections)} | "
            f"{format_long_duration(dur)} |"
        )
    if cmp["missing"]:
        lines += ["", "## Missing snapshot rows", "", ", ".join(map(str, cmp["missing"]))]
    if cmp["moved"]:
        lines += ["", "## Reordered", "", "| Selection | Snapshot pos | Now | Title |", "|---|---:|---:|---|"]
        lines += [f"| `{s.id}` | {a} | {b} | {s.title} |" for s, a, b in cmp["moved"]]
    if cmp["amended"]:
        lines += [
            "",
            "## Amended since snapshot",
            "",
            "| Selection | Snapshot pos | Fields |",
            "|---|---:|---|",
        ]
        lines += [f"| `{s.id}` | {p} | {', '.join(d)} |" for s, p, d in cmp["amended"]]
    if cmp["retired"]:
        lines += ["", "## Retired", ""]
        lines += [f"- `{s.id}` (snapshot pos {s.source_position}): {s.title}" for s in cmp["retired"]]
    if cmp["new"]:
        lines += ["", "## New", ""]
        lines += [f"- `{s.id}`: {s.title}" for s in cmp["new"]]
    return "\n".join(lines) + "\n"


def _guide_ranges(root: Path) -> dict[str, str]:
    text = (root / STUDENT_GUIDE).read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r"## \d+\s+(\w+).*?\*\*Playlist tracks\*\* — (\d+–\d+ · \d+ tracks)", text, re.S):
        out[m.group(1)] = m.group(2)
    return out


def editorial_report(root: Path, atlas: Atlas, c: Collection) -> str:
    positions = c.positions()
    by_id = {s.id: s for s in c.selections()} | {s.id: s for s in _retired_selections(c)}
    lines = [
        f"# Editorial discrepancy report — {c.title}",
        "",
        "Generated by `atlas audit` from `issues.yaml`, proposals and the data itself. Approved-but-unmerged",
        "changes are listed here; they are **not** reflected in the playlist until applied.",
        "",
        "## Open issues",
        "",
    ]
    for issue in c.issues:
        if issue.get("status") not in ("open", "partially_resolved"):
            continue
        lines.append(f"### {issue['id']} · {issue['title']} ({issue['status'].replace('_', ' ')})")
        lines.append("")
        lines.append(issue["detail"])
        lines.append("")
        sel_ids = issue.get("selections") or []
        if sel_ids:
            shown = sel_ids[:6]
            refs = []
            for sid in shown:
                s = by_id.get(sid)
                pos = positions.get(sid)
                refs.append(
                    f"`{sid}` (#{pos})" if pos else f"`{sid}` (retired)" if s else f"`{sid}` (unknown)"
                )
            more = f" … and {len(sel_ids) - len(shown)} more" if len(sel_ids) > len(shown) else ""
            lines.append(f"Selections: {', '.join(refs)}{more}")
            lines.append("")
        lines.append(f"**Action:** {issue['action']}")
        lines.append("")

    proposals = sorted((c.path / "proposals").glob("*.yaml"))
    if proposals:
        lines += ["## Proposals", ""]
        for p in proposals:
            res = check_proposal(atlas, c, yamlio.load(p))
            lines += res.markdown()
            lines.append("")

    guide = _guide_ranges(root)
    if guide:
        lines += [
            "## Student guide ranges vs current data",
            "",
            "| Stage | Guide says | Current |",
            "|---|---|---|",
        ]
        for st in c.stages:
            if not st.selections:
                continue
            first, last = positions[st.selections[0].id], positions[st.selections[-1].id]
            now = f"{first}–{last} · {len(st.selections)} tracks"
            flag = "" if guide.get(st.name) == now else " ⚠"
            lines.append(f"| {st.name} | {guide.get(st.name, '—')} | {now}{flag} |")
        lines.append("")

    stale = [st for st in c.stages if st.itinerary_source]
    if stale:
        lines += ["## Itinerary wording updated (originals preserved)", ""]
        for st in stale:
            lines += [f"- **{st.name}** — was: “{st.itinerary_source}”", f"  - now: “{st.itinerary}”"]
        lines.append("")

    if c.orphaned_notes:
        lines += ["## Orphaned notes", ""]
        lines += [f"- {n['source_key']}: {n['text']} — {n['reason']}" for n in c.orphaned_notes]
        lines.append("")

    unresolved = [s for s in c.selections() if match_status(s) != "exact_song_id"]
    lines += [f"## Selections without a verified Apple song ID ({len(unresolved)})", ""]
    groups: dict[str, list[Selection]] = {}
    for s in unresolved:
        groups.setdefault(s.recording, []).append(s)
    for rid, group in groups.items():
        rec = atlas.recordings[rid]
        span = (
            f"#{positions[group[0].id]}–{positions[group[-1].id]}"
            if len(group) > 1
            else f"#{positions[group[0].id]}"
        )
        lines.append(
            f"- **{rec.principal_artist} — {rec.album_title}** ({len(group)}, {span}): "
            f"{match_status(group[0])}"
        )
    return "\n".join(lines) + "\n"


def write_reports(root: Path, atlas: Atlas) -> list[Path]:
    out = []
    for c in atlas.collections:
        d = root / "reports" / c.id
        d.mkdir(parents=True, exist_ok=True)
        for name, text in (
            ("migration-report.md", migration_report(root, atlas, c)),
            ("editorial-discrepancies.md", editorial_report(root, atlas, c)),
        ):
            (d / name).write_text(text, encoding="utf-8", newline="\n")
            out.append(d / name)
    return out
